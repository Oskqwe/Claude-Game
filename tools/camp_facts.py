"""Build data/facts-camps.js from the 'Verify list' tables in docs/camps/*.md.
Status values: research, unchecked, open (still to read). Re-run after editing a brief."""
import re, json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
sec = {'major':'C','business':'D','docker':'E','firebrand':'F','middle':'G','planner':'H','pioneer':'I','machine':'J','mandarin':'K'}
out = {}
for camp, s in sec.items():
    text = (root/'docs/camps'/f'{camp}.md').read_text()
    part = text.split('## Verify list',1)[1]
    for m in re.finditer(r'^\| `([a-z0-9-]+)` \| (.+?) \| (.+?) \|$', part, re.M):
        fid, claim, status = m.groups()
        st = status.split()[0]
        if st not in ('research','unchecked','open'): st = 'unchecked'
        note = status[len(st):].strip(' ()')
        e = {'status': st, 'camp': camp, 'claim': claim.replace('`',''), 'sources': [f'RESEARCH.md §{s}'] if st=='research' else []}
        if note: e['note'] = note
        out[fid] = e
js = ['/* Fact register for the nine unbuilt camps. Generated by tools/camp_facts.py from docs/camps/*.md.',
      '   Same statuses as data/facts.js, plus "open": a figure or episode still to be read.',
      '   Not loaded by index.html until a camp is built. */',
      '(function () {','  const TM = (window.TM = window.TM || {});','  TM.FACTS = TM.FACTS || {};','  Object.assign(TM.FACTS, {']
for k,v in out.items(): js.append(f'    {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)},')
js += ['  });','})();','']
(root/'data/facts-camps.js').write_text('\n'.join(js))
from collections import Counter
print(len(out), Counter(v['status'] for v in out.values()))
